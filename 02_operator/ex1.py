# 산술 연산자
a = 10
b = 3
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)
print(4/2)
# 복합 대입 연산자
a += 4
print(a)
a -=2
print(a)
# 증강 연산자 없음
# a++
a+=1
# 비교 연산자
print(3 == 3.0)
print(3 != 4)
print("apple"< "banana")
print(1<2<3) # 1 < 2 and 2 < 3
print(1<3<2) # 1 < 3 and 3 < 2

# 논리 연산자(and,or)
a = True
b = False
print(a and b)
print(a or b)
print(not b)
print(not a)
# short_circuit 테스트
a= 10
b = 0